// Локальный планировщик: метод динамического окна (Dynamic Window Approach,
// Fox, Burgard, Thrun, 1997) с учётом движения препятствий.
//
// На каждом такте управления:
//   1. Строится динамическое окно — скорости (v, w), достижимые за ближайший
//      интервал времени при ограниченных ускорениях.
//   2. Для каждой пары (v, w) из окна моделируется дуга движения на горизонт
//      планирования. Дуга проверяется на столкновение со статическими
//      препятствиями (точки текущего скана) и с подвижными — с поправкой на их
//      перемещение: в момент t препятствие находится в точке p + u·t.
//   3. Допустимы только траектории, на которых робот успевает остановиться до
//      препятствия. Из допустимых выбирается лучшая по взвешенной сумме:
//      близость конца дуги к локальной цели, ориентация на цель, запас до
//      препятствий, скорость и время до столкновения. Последнее слагаемое нужно
//      именно из-за подвижных препятствий: остановка не спасает от объекта,
//      который едет на робота, и из «плохих» вариантов нужно выбирать тот, где
//      столкновение наступает позже или не наступает вовсе.
//
// Все координаты — в СК робота на момент вызова (ось X — вперёд).
#pragma once

#include <cstdint>
#include <span>
#include <vector>

#include "roversim/math.hpp"

namespace roversim::nav {

/// Подвижное препятствие в СК робота: круг, движущийся с постоянной скоростью.
struct MovingObstacle {
    Vec2 position;
    Vec2 velocity;
    double radius = 0.0;
};

struct DwaConfig {
    // --- Возможности робота ---
    double max_speed = 0.8;        ///< [м/с]
    double min_speed = 0.0;        ///< отрицательное значение разрешило бы задний ход; по умолчанию
                                   ///< он запрещён: иначе при цели за спиной робот пятится к ней,
                                   ///< вместо того чтобы развернуться
    double max_yaw_rate = 2.5;     ///< [рад/с]
    double max_accel = 1.5;        ///< разгон и торможение [м/с²]
    double max_yaw_accel = 6.0;    ///< [рад/с²]
    double robot_radius = 0.20;    ///< [м]
    // --- Поиск ---
    double window_time = 0.2;      ///< интервал, на который раскрывается окно скоростей [с]
    double horizon = 1.6;          ///< горизонт моделирования траектории [с]
    double time_step = 0.1;        ///< шаг моделирования [с]
    int speed_samples = 9;         ///< число значений v в окне
    int yaw_samples = 21;          ///< число значений w в окне
    double safety_margin = 0.05;   ///< минимальный зазор до препятствий [м]
    double moving_margin = 0.10;   ///< дополнительный зазор до подвижных препятствий [м]:
                                   ///< прогноз их движения неточен
    double escape_speed = -0.5;    ///< скорость отхода назад, разрешённая только при угрозе
                                   ///< со стороны подвижного препятствия [м/с]
    // --- Веса целевой функции ---
    double weight_goal = 1.0;      ///< близость конца траектории к локальной цели
    double weight_heading = 0.3;   ///< ориентация в конце траектории на цель
    double weight_clearance = 0.25; ///< запас до препятствий
    double weight_speed = 0.15;    ///< скорость движения вперёд
    double weight_survival = 1.5;  ///< доля горизонта без столкновения: уводит от препятствия,
                                   ///< которое само надвигается на робота
    double clearance_cap = 0.5;    ///< зазор больше этого не добавляет оценки [м]
    // --- Локальная сетка расстояний ---
    double grid_resolution = 0.05; ///< [м]
    double grid_half_size = 2.0;   ///< сетка покрывает квадрат ±grid_half_size вокруг робота [м]:
                                   ///< путь за горизонт на полной скорости плюс радиус и запас
};

struct DwaResult {
    double v = 0.0;          ///< выбранная линейная скорость [м/с]
    double w = 0.0;          ///< выбранная угловая скорость [рад/с]
    bool feasible = false;   ///< нашлась ли хоть одна допустимая траектория
    double clearance = 0.0;  ///< минимальный зазор на выбранной траектории [м]
    double score = 0.0;      ///< значение целевой функции
    int admissible = 0;      ///< число допустимых траекторий
};

class DwaPlanner {
 public:
    explicit DwaPlanner(const DwaConfig& config);

    /// obstacles — точки статических препятствий, moving — подвижные препятствия,
    /// target — локальная цель; v, w — текущие скорости робота.
    /// allow_reverse разрешает задний ход (до escape_speed) — для ухода от
    /// надвигающегося препятствия.
    DwaResult compute(std::span<const Vec2> obstacles, std::span<const MovingObstacle> moving, Vec2 target,
                      double v, double w, bool allow_reverse = false);

    const DwaConfig& config() const noexcept { return cfg_; }
    /// Точки выбранной траектории (для отладки и отрисовки).
    std::span<const Vec2> trajectory() const noexcept { return best_trajectory_; }

 private:
    double static_distance(Vec2 p) const noexcept;

    DwaConfig cfg_;
    int grid_size_;
    bool grid_empty_ = true;
    std::vector<std::uint8_t> mask_;
    std::vector<float> field_;  ///< расстояние до ближайшей точки препятствия, в клетках
    std::vector<Vec2> trajectory_, best_trajectory_;
};

}  // namespace roversim::nav
